// Variable
// A Variable is container that stores a value.

// Javascript is Dynamic Type Language (We can change its type)
var a = 67;
console.log(a, "a");
//    (a) is Identifier, (=) is Assignment operator (67) is Literal (Constant Value)
a = "Ali";
console.log(a, "a");

// Rules for choosing Variables names:-
// 1-Letters, Digits, Underscores and $ sign allowed.
// 2-Javascript reserved words cannot be used as variables.
// 3-Ali and ali are different varibales (case senstive).
